/** Real Chrome acceptance of orbit, touch gestures and linked staircase selection. */
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const url = process.env.BASE_URL ?? 'http://127.0.0.1:5173/';
const out = 'test-results/stairs-orbit';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH ?? ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, hasTouch: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('flooring-estimator:project:v1')).project.staircases[0]);
const view = page.locator('.stair-physical-view');
const svg = view.locator('.stair-physical-svg');
const button = name => view.getByRole('button', { name, exact: true });
const orbit = async () => ({ yaw: Number(await svg.getAttribute('data-orbit-yaw')), pitch: Number(await svg.getAttribute('data-orbit-pitch')), zoom: Number(await svg.getAttribute('data-orbit-zoom')) });
const facePoints = () => view.locator('[data-physical-face]').evaluateAll(faces => faces.map(face => face.getAttribute('points')));
const faceCentre = id => view.locator(`[data-physical-piece="${id}"][data-physical-face="surface"]`).evaluate(polygon => {
  const vertices = [...polygon.points];
  const point = new DOMPoint(vertices.reduce((sum, p) => sum + p.x, 0) / vertices.length, vertices.reduce((sum, p) => sum + p.y, 0) / vertices.length).matrixTransform(polygon.getScreenCTM());
  return { x: point.x, y: point.y };
});
try {
  await page.goto(url);
  await page.locator('nav.tabs').getByRole('button', { name: 'Rooms & stairs', exact: true }).click();
  await page.getByRole('button', { name: '+ Stairs', exact: true }).click();
  await view.waitFor();
  // Use a returning fixture independent of the starter-preset workflow.
  await page.evaluate(() => {
    const key = 'flooring-estimator:project:v1', stored = JSON.parse(localStorage.getItem(key));
    const stairs = stored.project.staircases[0];
    stairs.name = 'Orbit return'; stairs.landings = [];
    stairs.layout = { kind: 'half_turn', direction: 'right', turnStartIndex: 5, turnSteps: 3 };
    delete stairs.drawing;
    stairs.steps.forEach((step, index) => { delete step.plan; if (index >= 5 && index < 8) Object.assign(step, { kind: 'winder', going: 600, goingNarrow: 100 }); });
    localStorage.setItem(key, JSON.stringify(stored));
  });
  await page.reload();
  await page.locator('.sidebar-column button.list-row').filter({ hasText: 'Orbit return' }).click();
  await button('3D').click();
  await svg.scrollIntoViewIfNeeded();
  const measured = await stored(), initial = await orbit(), initialFaces = await facePoints();
  assert.deepEqual(initial, { yaw: -45, pitch: 60, zoom: 1 });
  const last = measured.steps.at(-1).id;
  const start = await faceCentre(last);
  await page.mouse.move(start.x, start.y); await page.mouse.down();
  await page.mouse.move(start.x + 100, start.y - 75, { steps: 12 }); await page.mouse.up();
  assert.notEqual((await orbit()).yaw, initial.yaw);
  assert((await orbit()).pitch < initial.pitch);
  assert.notDeepEqual(await facePoints(), initialFaces);
  assert.equal(await view.locator('.stair-physical-target.selected').count(), 0, 'Dragging a tread rotates without selecting it');
  await view.screenshot({ path: `${out}/01-orbited-return.png` });
  await button('Reset view').click();
  await svg.scrollIntoViewIfNeeded();
  const click = await faceCentre(last);
  await page.mouse.click(click.x, click.y);
  assert.equal(await view.locator(`[data-physical-target="${last}"]`).getAttribute('aria-pressed'), 'true');
  await svg.focus();
  for (let index = 0; index < 36; index++) await svg.press('ArrowRight');
  assert.equal((await orbit()).yaw, initial.yaw, 'Keyboard permits a complete turn');
  await svg.press('ArrowDown');
  assert.equal((await orbit()).pitch, 50);
  const box = await svg.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.wheel(0, -220);
  await page.waitForFunction(() => Number(document.querySelector('.stair-physical-svg').dataset.orbitZoom) > 1);
  await button('Reset view').click();
  assert.deepEqual(await orbit(), initial);
  await view.getByText('More viewing angles', { exact: true }).click();
  await button('View from below').click();
  assert((await orbit()).pitch < 0);
  assert.equal(await view.locator('[data-physical-face="underside"]').count(), measured.steps.length);
  assert.equal(await view.locator('[data-physical-face="surface"]').count(), 0);
  await view.screenshot({ path: `${out}/02-underside.png` });
  await button('View from above').click();
  assert.equal((await orbit()).pitch, 89);
  await button('View from back').click();
  assert.equal((await orbit()).yaw, 135);
  await button('Side').click();
  const side = await facePoints();
  await svg.dispatchEvent('wheel', { deltaY: -500 });
  assert.deepEqual(await facePoints(), side, 'Fixed elevations do not orbit or zoom');
  await button('3D').click(); await button('Reset view').click();
  await page.setViewportSize({ width: 390, height: 1080 });
  await svg.scrollIntoViewIfNeeded();
  const touchBox = await svg.boundingBox(), cx = touchBox.x + touchBox.width / 2, cy = touchBox.y + touchBox.height / 2;
  const cdp = await context.newCDPSession(page);
  const touch = (id, x, y) => ({ id, x, y, radiusX: 4, radiusY: 4, force: 1 });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touch(1, cx - 25, cy), touch(2, cx + 25, cy)] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [touch(1, cx - 55, cy), touch(2, cx + 55, cy)] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert((await orbit()).zoom > 1.8, 'Two fingers pinch to zoom');
  await button('Reset view').click(); await svg.scrollIntoViewIfNeeded();
  const phone = await svg.boundingBox(), x = phone.x + 30, y = phone.y + 35;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touch(3, x, y)] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [touch(3, x + 70, y + 20)] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.notEqual((await orbit()).yaw, initial.yaw, 'One finger turns the staircase');
  await view.screenshot({ path: `${out}/03-touch-orbit.png` });
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1080 });
    const size = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert(size.scroll <= size.width + 1, `Orbit controls overflow at ${width}px`);
  }
  assert.deepEqual(await stored(), measured, 'All view interactions preserve the measured staircase');
  assert.deepEqual(errors, []);
  console.log('PASS mouse orbit, complete keyboard turn, wheel/pinch zoom, underside/back/top views, fixed elevations, click vs drag selection, touch orbit, measured-data preservation and responsive layouts');
} finally { await browser.close(); }
