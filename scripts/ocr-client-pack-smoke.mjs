import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.env.BASE_URL ?? 'http://127.0.0.1:5173/';
const output = process.env.OUT_DIR ?? 'test-results/ocr-client-pack';
await mkdir(output, { recursive: true });
const executablePath = process.env.CHROMIUM_PATH ?? ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce', acceptDownloads: true });
const page = await context.newPage();
await page.addInitScript(() => {
  window.startedPlanReaders = [];
  const OriginalWorker = window.Worker;
  window.Worker = class extends OriginalWorker {
    constructor(url, options) {
      super(url, options);
      if (String(url).includes('planReading.worker')) window.startedPlanReaders.push(String(url));
    }
  };
});
page.setDefaultTimeout(20000);
const errors = [], external = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith(base)) external.push(request.url()); });
const pass = message => { checks.push(message); console.log('PASS', message); };
const project = () => page.evaluate(() => JSON.parse(localStorage.getItem('flooring-estimator:project:v1')).project);
const tab = name => page.locator('nav.tabs').getByRole('button', { name, exact: true });
const view = name => page.getByRole('navigation', { name: 'Estimate sections' }).getByRole('button', { name, exact: true });
const commit = async (label, value, scope = page) => { await scope.getByLabel(label, { exact: true }).fill(value); await scope.getByLabel(label, { exact: true }).press('Tab'); };
const tap = async (x, y) => { const box = await page.getByTestId('floorplan-overlay').boundingBox(); await page.mouse.click(box.x + x / 960 * box.width, box.y + y / 700 * box.height); };
const fits = async width => { await page.setViewportSize({ width, height: 1000 }); const sizes = await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth]); assert(sizes[0] <= sizes[1] + 1, `Overflow ${width}: ${sizes}`); };
try {
  await page.goto(base);
  await tab('Floor plan').click();
  await page.getByLabel('Upload a floor plan (PNG, JPG or PDF)', { exact: true }).setInputFiles('scripts/fixtures/estate-plan.svg');
  await page.getByAltText('Floor plan: estate-plan.svg', { exact: true }).waitFor();
  await tap(86, 90); await tap(434, 90);
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('flooring-estimator:project:v1')).project.floorPlans[0]?.reading?.source === 'ocr', null, { timeout: 65000 });
  assert.equal(await page.evaluate(() => window.startedPlanReaders.length), 1, 'Uploaded image must be read automatically once, without pressing a reading button');
  await page.getByTestId('plan-reader').locator('summary').first().click();
  await page.getByRole('button', { name: 'Read image again', exact: true }).waitFor({ timeout: 65000 });
  const read = (await project()).floorPlans[0].reading;
  assert(read?.source === 'ocr', 'Real OCR result is persisted');
  assert(/lounge/i.test(read.text), `OCR recognises fixture label: ${read?.text}`);
  assert(read.lines.some(line => /lounge/i.test(line.text) && line.width > 0 && line.height > 0));
  assert.equal((await project()).floorPlans[0].mmPerPx, undefined, 'OCR must not silently set scale');
  await page.getByTestId('plan-reader').getByText('Review or correct recognised text', { exact: true }).click();
  await page.getByTestId('plan-reader').getByText('Full text transcript', { exact: true }).click();
  await page.getByLabel('Recognised text', { exact: true }).fill(read.text.replace(/435m/g, '4.35m'));
  const length = page.getByTestId('plan-reader').getByRole('button', { name: /^4[.,]35\s*m$/i });
  assert.equal(await length.count(), 1, `OCR exposes printed length. Text was ${read.text}`);
  await length.click();
  assert.equal(await page.getByLabel('Known distance', { exact: true }).inputValue(), '4350mm');
  assert.equal((await project()).floorPlans[0].mmPerPx, undefined);
  await page.getByLabel('Known distance', { exact: true }).press('Enter');
  assert(Math.abs((await project()).floorPlans[0].mmPerPx - 12.5) < .02);
  await page.getByRole('button', { name: 'Rectangle', exact: true }).click();
  await tap(86, 86); await tap(434, 334);
  assert.equal(await page.getByLabel('Room name', { exact: true }).inputValue(), 'Lounge');
  await page.getByRole('button', { name: 'Add room', exact: true }).click();
  pass('Real local OCR runs automatically once; corrections update suggestions, reviewed scale and spatial naming work');
  assert.equal(external.length, 0, `OCR must stay on this origin: ${external}`);
  await page.screenshot({ path: `${output}/01-floorplan-ocr.png`, fullPage: true });
  await page.reload();
  await tab('Floor plan').click();
  assert.equal((await project()).floorPlans[0].reading.text, read.text.replace(/435m/g, '4.35m'));
  assert.equal(await page.evaluate(() => window.startedPlanReaders.length), 0, 'A persisted reading must be reused after reload');
  pass('Recognised text and bounding boxes survive browser persistence');

  await tab('Materials & options').click();
  await commit('Price per square metre', '28');
  await tab('Settings').click();
  await commit('Business name', 'Greenwood Floors');
  await commit('Business email', 'hello@example.test');
  await commit('Standard client terms', 'Installation date to be agreed with the client.');
  await page.getByLabel('Labour pricing method', { exact: true }).selectOption('hourly');
  await commit('Hourly labour rate', '42');
  await tab('Estimate').click();
  const total = await page.getByTestId('kpi-total').textContent();
  assert(await page.locator('#estimate-cutting').isHidden());
  await page.screenshot({ path: `${output}/02-estimate-overview.png`, fullPage: true });
  await view('Cutting plans').click();
  assert(await page.getByTestId('roll-cut-diagram').first().isVisible());
  assert(await page.locator('#estimate-summary').isHidden());
  await view('Client pack').click();
  const controls = page.locator('.client-pack-controls');
  await controls.locator('details.quote-details > summary').click();
  await commit('Customer', 'Alex Morgan', controls);
  await commit('Site address', '12 Example Road', controls);
  await commit('Quote reference', 'GF-001', controls);
  await commit('Quote date', '2026-09-07', controls);
  assert.equal(await page.getByTestId('client-pack').locator('.pack-grand-total strong').textContent(), total);
  assert(await page.getByTestId('client-pack').getByText('Greenwood Floors', { exact: true }).isVisible());
  assert.equal(await page.getByTestId('client-pack').locator('svg image').count(), 1);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download client pack', exact: true }).click();
  const download = await downloadPromise;
  const file = `${output}/client-pack.html`;
  await download.saveAs(file);
  const html = await readFile(file, 'utf8');
  assert(html.includes('@media print') && html.includes('data:image/png;base64,') && html.includes('Alex Morgan'));
  assert(!html.includes('<script'));
  pass('Client pack matches the estimate and downloads a styled standalone document with embedded plan');
  for (const width of [1024, 768, 390, 320]) { await fits(width); if (width === 390) await page.screenshot({ path: `${output}/03-client-pack-phone.png`, fullPage: true }); }
  await fits(1440);
  await page.screenshot({ path: `${output}/04-client-pack-desktop.png`, fullPage: true });
  await page.emulateMedia({ media: 'print' });
  assert(await page.getByTestId('client-pack').isVisible());
  assert(await page.locator('#estimate-summary').isHidden());
  assert(await page.locator('#estimate-cutting').isHidden());
  assert(await page.locator('.client-pack-controls').isHidden());
  await page.pdf({ path: `${output}/client-pack.pdf`, format: 'A4', printBackground: true });
  await page.emulateMedia({ media: 'screen' });
  pass('Client pack fits desktop and phone; PDF print contains the client proposal without internal sections');
  await view('Overview').click();
  await page.emulateMedia({ media: 'print' });
  assert(await page.locator('#estimate-summary').isVisible());
  assert(await page.locator('#estimate-cutting').isVisible());
  assert(await page.locator('#estimate-bom').isVisible());
  await page.emulateMedia({ media: 'screen' });
  pass('Internal estimate print still includes all technical sections');
  assert.equal(errors.length, 0, errors.join('\n'));
  await writeFile(`${output}/report.json`, JSON.stringify({ checks, errors, external, total, recognised: read.text }, null, 2));
} catch (error) { await page.screenshot({ path: `${output}/failure.png`, fullPage: true }); throw error; }
finally { await browser.close(); }
